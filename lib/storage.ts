import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";

// Uploaded files live outside the app's public folder and are only ever served
// through an authorised route. Names are generated here, never taken from users.
//
// Locally that is ./uploads. Vercel's deployment folder is read-only, so there it is the
// temp folder, which is per instance and not durable: fine for a demo, not for real use.
// UPLOAD_DIR is an optional override (the tests point it at a temp folder).
const uploadDir = () =>
  process.env.UPLOAD_DIR ??
  (process.env.VERCEL
    ? path.join(os.tmpdir(), "uploads")
    : path.resolve(/*turbopackIgnore: true*/ process.cwd(), "uploads"));

const KEY_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(pdf|docx)$/;

function pathFor(key: string): string {
  // Keys are generated by saveUpload; anything else never reaches the filesystem.
  if (!KEY_PATTERN.test(key)) throw new Error("Invalid storage key");
  return path.join(/*turbopackIgnore: true*/ uploadDir(), key);
}

// Writes the bytes under a random name and returns that name (the storage key).
export async function saveUpload(bytes: Uint8Array, extension: ".pdf" | ".docx"): Promise<string> {
  const key = `${randomUUID()}${extension}`;
  await mkdir(/*turbopackIgnore: true*/ uploadDir(), { recursive: true });
  await writeFile(/*turbopackIgnore: true*/ pathFor(key), bytes, { flag: "wx" });
  return key;
}

export async function readUpload(key: string): Promise<Buffer> {
  return readFile(/*turbopackIgnore: true*/ pathFor(key));
}

export async function deleteUpload(key: string): Promise<void> {
  await rm(/*turbopackIgnore: true*/ pathFor(key), { force: true });
}
